import math

tup1 = (4, 3, 2, 2, -1, 18)
tup2 = (2, 4, 8, 8, 3, 2, 9)

product_tup1 = math.prod(tup1)
product_tup2 = math.prod(tup2)

final_product = product_tup1 * product_tup2

print(f"Product of tup1: {product_tup1}")
print(f"Product of tup2: {product_tup2}")
print(f"Total product of all numbers: {final_product}")
