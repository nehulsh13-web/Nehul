set1 = {"Green","Blue", "Orange", "Red","Yellow"}
set2 = {"Dark Green", "Sky Blue", "Maroon","Blue"}
print("Original Sets: ")
print(set1)
print(set2)
print("Intersection of both sets :")
set3 = set1.intersection(set2)
print(set3)
set4 = set1.union(set2)
print("Union of both sets :")
print(set4)
set5 = set1.difference(set2)
print("The diffrence of both sets")
print (set5)
